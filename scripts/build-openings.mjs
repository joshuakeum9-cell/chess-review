/* Compile the Lichess ECO dataset into the app's opening book.
 *
 * Source: https://github.com/lichess-org/chess-openings (CC0), five TSV files
 * holding ~3800 named openings as SAN move sequences.
 *
 * The app needs to answer two questions fast:
 *   1. What is this opening called? (deepest match wins)
 *   2. Is this move still theory? (so it is not graded as a found move)
 *
 * Both are position questions, not move-sequence questions: transpositions
 * reach the same opening by different move orders and must be recognised.
 * So the book is keyed by a hash of the position, not by the SAN prefix the
 * old hand-written book used.
 *
 * Run: node scripts/build-openings.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from '../js/chess.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'bench', 'data');

/* FNV-1a over the part of the FEN that defines the position: pieces, side to
 * move, castling rights and en passant square. Clocks are excluded so the
 * same position reached by different routes hashes identically. */
function positionKey(fen) {
  const [board, turn, castling, ep] = fen.split(' ');
  const text = `${board} ${turn} ${castling} ${ep}`;
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
}

const rows = [];
for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const path = join(dataDir, `eco-${letter}.tsv`);
  if (!existsSync(path)) {
    console.error(`missing ${path}. Fetch the TSVs from lichess-org/chess-openings first.`);
    process.exit(1);
  }
  const text = readFileSync(path, 'utf8');
  for (const line of text.split('\n').slice(1)) {
    const [eco, name, pgn] = line.split('\t');
    if (!eco || !name || !pgn) continue;
    rows.push({ eco, name: name.trim(), pgn: pgn.trim() });
  }
}

const book = {};
let skipped = 0;

for (const row of rows) {
  const game = new Chess();
  const sans = row.pgn.replace(/\d+\.(\.\.)?/g, ' ').split(/\s+/).filter(Boolean);
  let ok = true;
  for (const san of sans) {
    if (!game.move(san)) {
      ok = false;
      break;
    }
  }
  if (!ok) {
    skipped++;
    continue;
  }
  const key = positionKey(game.fen());
  const entry = { n: row.name, e: row.eco, p: sans.length };
  // Several lines can reach the same position; keep the one whose name is
  // most specific, which is the longest line that got here.
  if (!book[key] || book[key].p < entry.p) book[key] = entry;
}

const out = `/* Generated by scripts/build-openings.mjs. Do not edit by hand.
 *
 * ${Object.keys(book).length} positions from the Lichess ECO dataset
 * (github.com/lichess-org/chess-openings, CC0), keyed by position hash so
 * transpositions resolve to the same opening.
 *
 * Each entry: n = name, e = ECO code, p = ply depth of the naming line.
 */
export const OPENING_POSITIONS = ${JSON.stringify(book)};
`;

writeFileSync(join(root, 'js', 'opening-data.js'), out);
console.log(
  `wrote js/opening-data.js: ${Object.keys(book).length} positions from ${rows.length} lines` +
    (skipped ? ` (${skipped} unparseable, skipped)` : '')
);
